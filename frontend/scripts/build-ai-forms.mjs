// Writes the handbook's table "Formulir yang bisa diisi AI" from the server's
// form catalog, so the handbook can never name a form the catalog does not
// have, or miss one it has: src/pages/handbook/aiForms.generated.js.
//
//   cd frontend && node scripts/build-ai-forms.mjs          write the file
//   cd frontend && node scripts/build-ai-forms.mjs --check  exit 1 when it is stale
//
// One table per module, one row per form:
//   form                 the catalog's title (the same text the AI's steps show)
//   dibuka dari          the title of the page its route opens (aiToolRegistry)
//   yang tetap Anda isi  the labels of the catalog's user-only fields
// The labels of user-only fields are in scripts/aiFormLabels.json (by field
// name, or one text for a whole form). A user-only field without a label
// stops the build: test/aiFormCoverage.test.js fails until it has one.
// After a change: scripts/i18n-extract.mjs (the texts are interface text),
// then build-handbook-docs.mjs and build-handbook-json.mjs.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const catalog = require('../../backend/src/services/ai/agent/formCatalog.js');
const registry = require('../../backend/src/services/aiToolRegistry.service.js');
const LABELS = JSON.parse(readFileSync(join(here, 'aiFormLabels.json'), 'utf8'));
export const OUT = join(here, '../src/pages/handbook/aiForms.generated.js');

const pageOf = (form) => {
  if (form.route.startsWith('<')) return LABELS.anyPage;
  const resolved = registry.resolveTool(form.route.split('?')[0].replace(/<[^<>]+>/g, '1'));
  if (!resolved) throw new Error(`build-ai-forms: ${form.id}: rute ${form.route} bukan halaman aplikasi`);
  return resolved.tool.title;
};

function keepsOf(form) {
  if (LABELS.forms[form.id]) return LABELS.forms[form.id];
  const labels = [];
  for (const name of form.fields.userOnly) {
    const label = LABELS.fields[name];
    if (!label) throw new Error(`build-ai-forms: ${form.id}: kolom "${name}" belum punya label di scripts/aiFormLabels.json`);
    if (!labels.includes(label)) labels.push(label);
  }
  return labels.length ? labels.join(', ') : LABELS.nothing;
}

export function buildAiForms() {
  const modules = [...new Set(catalog.FORMS.map((form) => form.module))];
  for (const module of modules) if (!LABELS.modules[module]) throw new Error(`build-ai-forms: modul "${module}" belum punya nama di scripts/aiFormLabels.json`);
  const order = [...LABELS.moduleOrder.filter((module) => modules.includes(module)), ...modules.filter((module) => !LABELS.moduleOrder.includes(module))];
  return order.map((module) => ({
    title: `Formulir yang bisa diisi AI: ${LABELS.modules[module]}`,
    rows: catalog.FORMS.filter((form) => form.module === module).map((form) => [form.title, pageOf(form), keepsOf(form)]),
  }));
}

const text = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
export function serialize(groups) {
  const total = groups.reduce((sum, group) => sum + group.rows.length, 0);
  const lines = [
    '// GENERATED by scripts/build-ai-forms.mjs from the server\'s form catalog',
    '// (backend/src/services/ai/agent/forms/*.js) — do not edit by hand.',
    '// cd frontend && node scripts/build-ai-forms.mjs',
    `export const AI_FORM_COUNT = ${total};`,
    'export const AI_FORM_TABLES = [',
  ];
  for (const group of groups) {
    lines.push('  {', `    title: ${text(group.title)},`, '    rows: [');
    for (const row of group.rows) lines.push(`      [${row.map(text).join(', ')}],`);
    lines.push('    ],', '  },');
  }
  lines.push('];', '');
  return lines.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const next = serialize(buildAiForms());
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch { /* missing = stale */ }
    if (current !== next) { console.error('aiForms.generated.js is stale: cd frontend && node scripts/build-ai-forms.mjs'); process.exit(1); }
    console.log('aiForms.generated.js is current');
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote ${OUT}`);
  }
  // The catalog pulls in the API's services (a database pool, timers): end the script here.
  process.exit(0);
}
